//! initramfs — embedded initial filesystem populated at boot.
//!
//! Contains a minimal user-mode ELF program (`/bin/hello`) that is
//! written into the root tmpfs during kernel initialisation. This
//! demonstrates the full VFS → execve → Ring3 user process pipeline
//! without requiring a real disk driver.

use super::tmpfs;

/// Minimal x86_64 ELF64 user program: write("Hello from /bin/hello!\n") then exit(0).
/// Uses int 0x80 with the AeroOS syscall numbers (write=3, exit=11).
/// Load address 0x400000, entry 0x400078.
pub const HELLO_ELF: &[u8] = &[
    0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x3e, 0x00, 0x01, 0x00, 0x00, 0x00, 0x78, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x38, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00,
    0xb9, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xb9, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // ── code at offset 0x78 (vaddr 0x400078) ──
    0x48, 0xc7, 0xc0, 0x03, 0x00, 0x00, 0x00, // mov rax, 3 (aeros write)
    0x48, 0xc7, 0xc7, 0x01, 0x00, 0x00, 0x00, // mov rdi, 1 (stdout)
    0x48, 0x8d, 0x35, 0x15, 0x00, 0x00, 0x00, // lea rsi, [rip+0x15]
    0x48, 0xc7, 0xc2, 0x16, 0x00, 0x00, 0x00, // mov rdx, 22
    0xcd, 0x80,                                   // int 0x80
    0x48, 0xc7, 0xc0, 0x0b, 0x00, 0x00, 0x00, // mov rax, 11 (aeros exit)
    0x48, 0x31, 0xff,                             // xor rdi, rdi
    0xcd, 0x80,                                   // int 0x80
    // ── string data ──
    b'H', b'e', b'l', b'l', b'o', b' ', b'f', b'r', b'o', b'm', b' ',
    b'/', b'b', b'i', b'n', b'/', b'h', b'e', b'l', b'l', b'o', b'!', b'\n',
];

/// Populate the root tmpfs with initramfs files.
pub fn init() {
    // Create /bin directory.
    if let Err(e) = tmpfs::mkdir("/bin") {
        crate::serial::_print(format_args!("[initramfs] mkdir /bin failed: {}\n", e));
        return;
    }

    // Write /bin/hello ELF.
    if let Err(e) = tmpfs::create_file_with_data("/bin/hello", HELLO_ELF) {
        crate::serial::_print(format_args!("[initramfs] write /bin/hello failed: {}\n", e));
        return;
    }

    crate::serial::_print(format_args!(
        "[initramfs] populated /bin/hello ({} bytes ELF64)\n",
        HELLO_ELF.len()
    ));
}
