/// Populate the root tmpfs with initramfs files.
pub fn init() {
    // Create /bin directory.
    if let Err(e) = tmpfs::mkdir("/bin") {
        crate::serial::_print(format_args!("[initramfs] mkdir /bin failed: {}\n", e));
        return;
    }

    // Write /bin/hello ELF.
    if let Err(e) = tmpfs::create_file_with_data("/bin/hello", HELLO_ELF) {
        crate::serial::_print(format_args!("[initramfs] write /bin/hello failed: {}\n", e));
        return;
    }

    // Write /bin/forktest ELF.
    if let Err(e) = tmpfs::create_file_with_data("/bin/forktest", FORKTEST_ELF) {
        crate::serial::_print(format_args!("[initramfs] write /bin/forktest failed: {}\n", e));
        return;
    }

    crate::serial::_print(format_args!(
        "[initramfs] populated /bin/hello ({} bytes ELF64), /bin/forktest ({} bytes ELF64)\n",
        HELLO_ELF.len(),
        FORKTEST_ELF.len()
    ));
}
